#!/usr/bin/env node
/**
 * Embeds the Bootstrap Icons used by Doku as inline SVG path data.
 *
 * Source: the `bootstrap-icons` npm package (devDependency only). The output
 * is a committed TypeScript module, so the packaged app carries the glyphs
 * inside its own renderer bundle and needs no CDN, icon font, or runtime
 * node_modules. Run `npm run icons:bootstrap` after editing the manifest;
 * `npm run icons:bootstrap -- --check` fails when the module is stale.
 */
const fs = require('node:fs');
const path = require('node:path');

const repoRoot = path.resolve(__dirname, '..');
const manifestPath = path.join(repoRoot, 'packages/ui/src/icons/bootstrap-icons.manifest.json');
const outputPath = path.join(repoRoot, 'packages/ui/src/icons/bootstrapIcons.generated.ts');
const packageDir = path.join(repoRoot, 'node_modules/bootstrap-icons');

function readManifest() {
  const names = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  if (!Array.isArray(names) || names.some((name) => typeof name !== 'string' || !/^[a-z0-9-]+$/.test(name))) {
    throw new Error(`Invalid icon manifest: ${manifestPath}`);
  }
  const unique = [...new Set(names)].sort();
  if (unique.length !== names.length) {
    throw new Error('Icon manifest contains duplicates');
  }
  return unique;
}

/** Parses one bootstrap-icons SVG into its `<path>` list. */
function parseIcon(name) {
  const file = path.join(packageDir, 'icons', `${name}.svg`);
  if (!fs.existsSync(file)) {
    throw new Error(`Unknown Bootstrap icon "${name}" (${file})`);
  }
  const svg = fs.readFileSync(file, 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (viewBox !== '0 0 16 16') {
    throw new Error(`Unexpected viewBox for "${name}": ${viewBox}`);
  }
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const paths = [];
  const remaining = body.replace(/<path\b([^>]*?)\/>/g, (_match, attributes) => {
    const d = /\bd="([^"]+)"/.exec(attributes)?.[1];
    if (!d) {
      throw new Error(`Path without "d" in "${name}"`);
    }
    const fillRule = /\bfill-rule="([^"]+)"/.exec(attributes)?.[1];
    const unknown = attributes.replace(/\bd="[^"]+"/, '').replace(/\bfill-rule="[^"]+"/, '').trim();
    if (unknown) {
      throw new Error(`Unsupported path attributes in "${name}": ${unknown}`);
    }
    paths.push(fillRule ? { d, fillRule } : { d });
    return '';
  });
  if (remaining.trim()) {
    throw new Error(`Unsupported SVG content in "${name}": ${remaining.trim().slice(0, 80)}`);
  }
  if (paths.length === 0) {
    throw new Error(`No paths found in "${name}"`);
  }
  return paths;
}

function render(names) {
  const version = JSON.parse(fs.readFileSync(path.join(packageDir, 'package.json'), 'utf8')).version;
  const lines = [
    '// Generated by scripts/generate-bootstrap-icons.cjs — do not edit by hand.',
    `// Source: bootstrap-icons ${version} (MIT). Regenerate with \`npm run icons:bootstrap\`.`,
    '',
    'export interface BootstrapIconPath {',
    '  readonly d: string;',
    "  readonly fillRule?: 'evenodd' | 'nonzero';",
    '}',
    '',
    `export const BOOTSTRAP_ICONS_VERSION = '${version}';`,
    '',
    'export const BOOTSTRAP_ICON_PATHS = {',
  ];
  for (const name of names) {
    const paths = parseIcon(name);
    lines.push(`  '${name}': [`);
    for (const entry of paths) {
      const fill = entry.fillRule ? `, fillRule: '${entry.fillRule}'` : '';
      if (entry.d.includes("'") || entry.d.includes("\\")) throw new Error(`Unexpected quote in path of "${name}"`);
      lines.push(`    { d: '${entry.d}'${fill} },`);
    }
    lines.push('  ],');
  }
  lines.push('} as const satisfies Record<string, readonly BootstrapIconPath[]>;', '');
  lines.push('export type BootstrapIconName = keyof typeof BOOTSTRAP_ICON_PATHS;', '');
  lines.push(
    'export const BOOTSTRAP_ICON_NAMES = Object.keys(BOOTSTRAP_ICON_PATHS) as readonly BootstrapIconName[];',
    '',
  );
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const names = readManifest();
  const next = render(names);
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : null;
  if (check) {
    if (current !== next) {
      console.error(`[generate-bootstrap-icons] ${path.relative(repoRoot, outputPath)} is stale. Run: npm run icons:bootstrap`);
      process.exit(1);
    }
    console.log(`[generate-bootstrap-icons] ${names.length} icons up to date`);
    return;
  }
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, next, 'utf8');
  console.log(`[generate-bootstrap-icons] wrote ${names.length} icons to ${path.relative(repoRoot, outputPath)}`);
}

if (require.main === module) {
  main();
}

module.exports = { readManifest, parseIcon, render, manifestPath, outputPath };
